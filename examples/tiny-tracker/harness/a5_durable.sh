#!/usr/bin/env bash
# The durable A5 run (tiny-tracker 0.3.0, gate G2): the contract's delayed
# recovery leg, against a durable build with control off (fixture clock off,
# offset 0, no fault listener) and a restart in the middle of the 24-hour
# window. Plan and procedure: docs/a5-durable.md.
#
#   A5_DIR=~/a5-run CONTRACT_DIR=~/contract-92bf1ba harness/a5_durable.sh start
#   harness/a5_durable.sh plant      # A1-A5 with the driver; A5 is planted (unproven today)
#   harness/a5_durable.sh restart    # some hours later, before due_at: stop, start again on the same data dir
#   harness/a5_durable.sh check      # read-only: /build, and the planted K and receipt id still answer
#   harness/a5_durable.sh delayed    # at or after due_at: the driver's --delayed-leg on the plant
#   harness/a5_durable.sh recount    # export, ledger, executions and journal through tt_recount.py
#   harness/a5_durable.sh stop
#
# Settings (environment; every one but A5_DIR and CONTRACT_DIR has a default):
#   A5_DIR        the run folder: data dir, token dir, driver copy, run output, state (created 0700)
#   CONTRACT_DIR  a checkout of the contract repository at the pinned commit (harness/contract.json)
#   A5_MCP_PORT, A5_BACKEND_PORT   fixed ports, so the plant's endpoint stays valid across the restart
#                 (default 4710 and 4711; never 47310/47311)
#   A5_DELAY_HOURS  the A5 window (default 24); a short value (0.01) is for rehearsals only
#   A5_FORCE=1    `delayed` before due_at: a rehearsal only, never a scored A5
#
# Tokens: the backend token is generated once into A5_DIR/backend.token (0600) and given to the process in
# its environment; the evidence token is generated by tiny-tracker into the token dir (--token-dir). No token
# is put on a command line or printed.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
CLI="$ROOT/dist/src/cli.js"
: "${A5_DIR:?set A5_DIR to the run folder}"
MCP_PORT="${A5_MCP_PORT:-4710}"
BACKEND_PORT="${A5_BACKEND_PORT:-4711}"
FEATURES="evidence,strict-input,ledger,durable,inflight,retention"
DATA="$A5_DIR/data"
TOKENS="$A5_DIR/tokens"
RUNS="$A5_DIR/runs"
DRIVER="$A5_DIR/driver"
LOG="$A5_DIR/a5.log"

say() { printf 'a5_durable: %s\n' "$*" | tee -a "$LOG" >&2; }
die() { say "$*"; exit 1; }
now() { date -u +%Y-%m-%dT%H:%M:%SZ; }

for p in "$MCP_PORT" "$BACKEND_PORT"; do
  [[ "$p" == 47310 || "$p" == 47311 ]] && die "ports 47310 and 47311 are reserved; choose others"
done

start_cmd() {
  echo "tiny-tracker all --features $FEATURES --data-dir $DATA --token-dir $TOKENS --port $MCP_PORT --backend-port $BACKEND_PORT"
}

evidence() { # GET <path> on the backend with the evidence token, body to stdout
  local token
  token="$(cat "$TOKENS/evidence.token")"
  curl -sS --fail-with-body -H "@-" "http://127.0.0.1:$BACKEND_PORT$1" <<<"authorization: Bearer $token"
}

launch() {
  [[ -f "$A5_DIR/backend.token" ]] || die "no backend token: run start first"
  local n="$1"
  TRACKER_BACKEND_TOKEN="$(cat "$A5_DIR/backend.token")" \
    nohup node "$CLI" all --features "$FEATURES" --data-dir "$DATA" --token-dir "$TOKENS" \
      --port "$MCP_PORT" --backend-port "$BACKEND_PORT" >"$A5_DIR/stdout.$n" 2>"$A5_DIR/stderr.$n" &
  echo $! >"$A5_DIR/pid"
  for _ in $(seq 1 100); do
    [[ -s "$A5_DIR/stdout.$n" ]] && break
    kill -0 "$(cat "$A5_DIR/pid")" 2>/dev/null || die "the build stopped at start: $(cat "$A5_DIR/stderr.$n")"
    sleep 0.1
  done
  head -1 "$A5_DIR/stdout.$n" >"$A5_DIR/state.json"
  cp "$A5_DIR/state.json" "$A5_DIR/state.$n.json"
  evidence /build >"$A5_DIR/build.$n.json"
  python3 -I - "$A5_DIR/build.$n.json" <<'PY' || die "the build is not the scored A5 posture (see a5.log)"
import json, sys
d = json.load(open(sys.argv[1]))
problems = []
if d["clock"].get("offset_ms") != 0 or d["clock"].get("domain") != "wall":
    problems.append("clock %r: a scored A5 run needs the wall clock, offset 0" % d["clock"])
if d["control"].get("enabled"):
    problems.append("control is on: a scored A5 run has control off")
if d["durability"].get("mode") != "journal":
    problems.append("durability %r: the run needs the journal" % d["durability"])
if d["faults"].get("armed"):
    problems.append("faults armed: %r" % d["faults"]["armed"])
for p in problems:
    print("a5_durable: " + p, file=sys.stderr)
print("a5_durable: build %s boot %s restart_count %s journal %s" % (d["build_hash"][:16], d["process"]["boot_id"], d["process"]["restart_count"], d["journal"]["head"]), file=sys.stderr)
sys.exit(1 if problems else 0)
PY
  say "started ($(start_cmd)), pid $(cat "$A5_DIR/pid")"
}

halt() {
  [[ -f "$A5_DIR/pid" ]] || return 0
  local pid
  pid="$(cat "$A5_DIR/pid")"
  if kill -0 "$pid" 2>/dev/null; then
    kill -TERM "$pid"
    for _ in $(seq 1 100); do kill -0 "$pid" 2>/dev/null || break; sleep 0.1; done
    kill -0 "$pid" 2>/dev/null && die "process $pid did not stop on SIGTERM"
  fi
  rm -f "$A5_DIR/pid"
  say "stopped process $pid"
}

plant_file() {
  local f
  f="$(ls -1 "$RUNS"/*/a5_plant.json 2>/dev/null | tail -1)"
  [[ -n "$f" ]] || die "no a5_plant.json: run plant first"
  echo "$f"
}

case "${1:-}" in
  start)
    : "${CONTRACT_DIR:?set CONTRACT_DIR to the contract checkout at the pinned commit}"
    mkdir -p "$A5_DIR" && chmod 700 "$A5_DIR"
    [[ -e "$DATA" ]] && die "$DATA exists: a new run starts with a new data dir (use restart for this one)"
    mkdir -p -m 700 "$TOKENS" "$RUNS"
    ( umask 077; node -e 'process.stdout.write("a5-backend-" + require("crypto").randomBytes(20).toString("hex"))' >"$A5_DIR/backend.token" )
    # The driver runs from a copy of the contract's harness with the tiny-tracker adapter beside it, kept for the
    # delayed leg (the plant names the adapter, and the delayed leg loads it from the same folder).
    pin="$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1]))["contract"]["commit"])' "$HERE/contract.json" 2>/dev/null || true)"
    have="$(git -C "$CONTRACT_DIR" rev-parse HEAD 2>/dev/null || echo unknown)"
    [[ -z "$pin" || "$have" == "$pin" ]] || die "the contract checkout is at $have, not the pinned $pin"
    cp -R "$CONTRACT_DIR/fixtures/harness" "$DRIVER"
    cp "$HERE/adapters/tiny_tracker.py" "$DRIVER/adapters/tiny_tracker.py"
    echo "$(start_cmd)" >"$A5_DIR/start.cmd"
    launch 0
    ;;
  plant)
    python3 -I "$HERE/adapter_config.py" --state "$A5_DIR/state.json" --fault client --delay-hours "${A5_DELAY_HOURS:-24}" --start "$(start_cmd)" >"$A5_DIR/config.json"
    out="$RUNS/$(date -u +%Y%m%dT%H%M%SZ)"
    TRACKER_EVIDENCE_TOKEN_FILE="$TOKENS/evidence.token" \
      python3 -I "$DRIVER/lost_response.py" --config "$A5_DIR/config.json" --out "$out" | tee -a "$LOG"
    python3 -I -c 'import json,sys; p=json.load(open(sys.argv[1])); print("a5_durable: planted K=%s receipts=%s due_at=%s" % (p["K"], p.get("execution_receipt_ids"), p.get("due_at")))' "$out/a5_plant.json" | tee -a "$LOG"
    ;;
  restart)
    plant="$(plant_file)"
    n=$(( $(ls -1 "$A5_DIR"/state.*.json | wc -l) ))
    # The ledger is kept in memory (one boot): recount while this boot's ledger is whole, before the stop.
    "$0" recount >"$A5_DIR/recount.before-restart.$n.txt" 2>&1 || true
    say "recount before restart $n: $(tail -2 "$A5_DIR/recount.before-restart.$n.txt" | head -1)"
    halt
    launch "$n"
    "$0" check
    ;;
  check)
    plant="$(plant_file)"
    evidence /build >"$A5_DIR/build.now.json"
    python3 -I -c 'import json,sys; a=json.load(open(sys.argv[1])); b=json.load(open(sys.argv[2])); assert a["build_hash"]==b["build_hash"], "build_hash changed"; print("a5_durable: same build_hash; boot %s -> %s; restart_count %s; journal %s; clock %s" % (a["process"]["boot_id"], b["process"]["boot_id"], b["process"]["restart_count"], b["journal"]["head"], b["clock"]))' "$A5_DIR/build.0.json" "$A5_DIR/build.now.json" | tee -a "$LOG"
    K="$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1]))["K"])' "$(plant_file)")"
    X="$(python3 -I -c 'import json,sys; print((json.load(open(sys.argv[1])).get("execution_receipt_ids") or [""])[0])' "$(plant_file)")"
    evidence "/operations/$K" >/dev/null && say "GET /operations/<K>: 200"
    [[ -n "$X" ]] && evidence "/executions/$X" >/dev/null && say "GET /executions/$X: 200"
    ;;
  delayed)
    plant="$(plant_file)"
    due="$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1]))["due_at"])' "$plant")"
    if [[ "$(now)" < "$due" && "${A5_FORCE:-0}" != 1 ]]; then die "due_at is $due (now $(now)); the delayed leg runs at or after it"; fi
    [[ "${A5_FORCE:-0}" == 1 ]] && say "A5_FORCE=1: a rehearsal before due_at; the result is not a scored A5"
    # Contract main's delayed leg dispatches nothing: it reads the K-only lookup it makes and the recorded delayed
    # retries and counts in the plant's folder. The probe writes those through the adapter (identical retry,
    # changed-argument retry, counts before / between / after), then the driver scores.
    TRACKER_EVIDENCE_TOKEN_FILE="$TOKENS/evidence.token" \
      python3 -I "$HERE/a5_delayed_probe.py" --driver "$DRIVER" --plant "$plant" | tee -a "$LOG"
    TRACKER_EVIDENCE_TOKEN_FILE="$TOKENS/evidence.token" \
      python3 -I "$DRIVER/lost_response.py" --delayed-leg "$plant" | tee -a "$LOG"
    evidence /build >"$A5_DIR/build.delayed.json"
    python3 -I -c 'import json,sys; d=json.load(open(sys.argv[1])); print("a5_durable: at the delayed leg: clock %s, control %s, restart_count %s" % (d["clock"], d["control"], d["process"]["restart_count"]))' "$A5_DIR/build.delayed.json" | tee -a "$LOG"
    ;;
  recount)
    for p in "export" "ledger" "executions"; do evidence "/$p?principal=p-default" >"$A5_DIR/$p.json"; done
    python3 -I "$ROOT/verify/python/tt_recount.py" --export "$A5_DIR/export.json" --ledger "$A5_DIR/ledger.json" \
      --executions "$A5_DIR/executions.json" --journal "$DATA/journal.jsonl" --principal p-default | tee -a "$LOG" || true
    say "the ledger is kept in memory: after a restart it holds only that boot's entries, so ledger-versus-journal disagreements for writes made before the restart are expected; the journal and the execution records must agree"
    ;;
  stop)
    halt
    ;;
  *)
    sed -n '2,25p' "$0"
    exit 2
    ;;
esac
