#!/usr/bin/env node
// Generates .github/ISSUE_TEMPLATE/comment.yml, the issue form "Comment on MWS 0.9", from spec/mws.md.
//
// The options of the `requirement` dropdown are the requirement IDs in the order of Annex C (requirement
// index), after a first option for the whole specification. The script checks that Annex C and the
// `#### MWS-…` headings of section 9 list the same IDs in the same order, and stops if they do not.
//
// The field ids (requirement, kind, comment, proposal, evidence) are fixed: links on isokron.ai prefill
// them. Do not rename them.
//
// Usage (from the repository root):
//   node scripts/gen-comment-form.mjs            write the form
//   node scripts/gen-comment-form.mjs --check    exit 1 if the form on disk differs from the generated one
// Options: --spec <path> (default spec/mws.md), --out <path> (default .github/ISSUE_TEMPLATE/comment.yml).

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? resolve(args[i + 1]) : resolve(root, fallback);
};
const specPath = opt("--spec", "spec/mws.md");
const outPath = opt("--out", ".github/ISSUE_TEMPLATE/comment.yml");
const check = args.includes("--check");

const fail = (msg) => {
  console.error(`gen-comment-form: ${msg}`);
  process.exit(1);
};

const spec = readFileSync(specPath, "utf8");
const lines = spec.split("\n");
const ID = /^MWS-[A-Z]+-\d+$/;

// Section 9 headings, in document order, up to section 10.
const s9Start = lines.findIndex((l) => /^## 9\. /.test(l));
const s10Start = lines.findIndex((l) => /^## 10\. /.test(l));
if (s9Start < 0 || s10Start < 0) fail("section 9 or 10 heading not found");
const headingIds = lines
  .slice(s9Start, s10Start)
  .map((l) => l.match(/^#### (MWS-[A-Z]+-\d+)\s*$/))
  .filter(Boolean)
  .map((m) => m[1]);

// Annex C table rows, in table order.
const cStart = lines.findIndex((l) => /^## Annex C\b/.test(l));
if (cStart < 0) fail("Annex C heading not found");
const cEnd = lines.findIndex((l, i) => i > cStart && /^## /.test(l));
const annexIds = lines
  .slice(cStart, cEnd < 0 ? undefined : cEnd)
  .map((l) => l.match(/^\|\s*(MWS-[A-Z]+-\d+)\s*\|/))
  .filter(Boolean)
  .map((m) => m[1]);

if (annexIds.length === 0) fail("no requirement rows found in Annex C");
if (new Set(annexIds).size !== annexIds.length) fail("Annex C lists an ID twice");
if (!annexIds.every((id) => ID.test(id))) fail("Annex C has a malformed ID");
if (annexIds.join(",") !== headingIds.join(",")) {
  const onlyC = annexIds.filter((id) => !headingIds.includes(id));
  const only9 = headingIds.filter((id) => !annexIds.includes(id));
  fail(
    `Annex C and section 9 differ (only in Annex C: ${onlyC.join(" ") || "none"}; ` +
      `only in section 9: ${only9.join(" ") || "none"}; otherwise the order differs)`,
  );
}

const q = (s) => JSON.stringify(s); // a JSON string is a valid YAML double-quoted scalar
const GENERAL = "General / whole specification";
const KINDS = [
  "The requirement is wrong",
  "It is unclear",
  "Something is missing",
  "Evidence or a counter-example",
  "Question",
  "Other",
];
const REPO = "https://github.com/isokron-ai/mcp-write-safety";

const form = `# Generated by scripts/gen-comment-form.mjs from spec/mws.md (Annex C). Do not edit by hand:
# change the script or the specification and run \`node scripts/gen-comment-form.mjs\`.
# The field ids are fixed; links on isokron.ai prefill them.
name: Comment on MWS 0.9
description: Comment on the MCP Write-Safety Requirements, version 0.9 (open until 16 December 2026).
title: "[MWS 0.9 comment] "
labels: ["comment-0.9", "triage:needs-reply"]
body:
  - type: markdown
    attributes:
      value: |
        Comments on MWS 0.9 are open from 16 November to 16 December 2026. Every comment gets a recorded disposition in the [disposition log](${REPO}/blob/main/spec/COMMENTS-0.9.md). A comment needs no particular form: this one only helps us sort it, and you need not write the change yourself. A proposal for new requirement text can also follow the proposal form in [CONTRIBUTING.md](${REPO}/blob/main/CONTRIBUTING.md).

        Issues in this repository are public. Do not use this form to report a vulnerability, in the test suite, in the sample server or in anyone else's server: see the [Security section of CONTRIBUTING.md](${REPO}/blob/main/CONTRIBUTING.md#security).
  - type: dropdown
    id: requirement
    attributes:
      label: Requirement
      description: The requirement your comment is about (Annex C of the specification lists them), or the whole specification.
      options:
${[GENERAL, ...annexIds].map((o) => `        - ${q(o)}`).join("\n")}
    validations:
      required: true
  - type: dropdown
    id: kind
    attributes:
      label: Kind of comment
      options:
${KINDS.map((o) => `        - ${q(o)}`).join("\n")}
    validations:
      required: true
  - type: textarea
    id: comment
    attributes:
      label: Comment
      description: What you think is wrong, unclear or missing, or what you want to ask. Quote the sentence you mean where you can.
    validations:
      required: true
  - type: textarea
    id: proposal
    attributes:
      label: Proposed text
      description: Optional. The wording you would use instead, or the sentence you would add.
    validations:
      required: false
  - type: input
    id: evidence
    attributes:
      label: Evidence
      description: Optional. A link to a public finding, an upstream issue or a failing case.
      placeholder: https://
    validations:
      required: false
`;

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (current !== form) fail(`${outPath} is out of date; run node scripts/gen-comment-form.mjs`);
  console.log(`gen-comment-form: ${outPath} is up to date (${annexIds.length} requirements)`);
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, form);
  console.log(`gen-comment-form: wrote ${outPath} (${annexIds.length} requirements + general)`);
}
